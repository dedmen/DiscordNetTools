        // This is called for ALL Modals, the name and interaction are registered in AutoGeneratedModalHandler
        public async Task HandleModalSubmit(IModalWithValidation modal)
        {
            var validation = await modal.Validate(Context);

            // We first validate, then save. Because Validation could make edits

            if (modal.SaveToDb)
            {
                var found = await ModalDataLookupFunction.Invoke(Context, modal.GetType().Name);
                if (found == null)
                {
                    var data = System.Text.Json.JsonSerializer.SerializeToNode(modal, modal.GetType(), ModalToolsSerializerOptions) as JsonObject;


                    await ModalDataStoreFunction.Invoke(Context, modal.GetType().Name, new UserDiscordModalContent
                    {
                        DiscordUserId = Context.User.Id,
                        ModalName = modal.GetType().Name,
                        Data = data
                    });
                }
                else
                {
                    found.Data = System.Text.Json.JsonSerializer.SerializeToNode(modal, modal.GetType(), ModalToolsSerializerOptions) as JsonObject;
                    await ModalDataStoreFunction.Invoke(Context, modal.GetType().Name, found);
                }
            }

            var multiType = ModalDirectory.Instance.GetMultiModalTypeFromModal(modal.GetType());

            if (!validation.Success)
            {
                // We cannot retry, see ButtonOpenModal main problem is that we cannot delete the button AND send a new modal at the same time. But we have to delete the button because the user can click multiple times
                //#TODO we can edit/delete the previous message can't we?

                var validationErrorHandlerContinuation = ValidationErrorHandlerContinuation.PresentToUser;
                if (multiType.GetInterface(nameof(IMultiStepInteractionValidationErrorHandler)) != null)
                {
                    validationErrorHandlerContinuation = await (multiType?.InvokeMember(nameof(IMultiStepInteractionValidationErrorHandler.OnValidationError),
                        BindingFlags.Static | BindingFlags.Public | BindingFlags.InvokeMethod, null, null,
                        new object[] { Context, validation, modal }) as Task<ValidationErrorHandlerContinuation>);

                }

                switch (validationErrorHandlerContinuation)
                {
                    case ValidationErrorHandlerContinuation.PresentToUser:
                        // Forward the message to the user
                        //var builder = new ComponentBuilder().WithButton("Try Again", $"_openModal_{(Context.Interaction as IModalInteraction).Data.CustomId}");
                        await RespondAsync(validation.Message/*, components: builder.Build()*/, ephemeral: true);
                        return; // No next step
                    case ValidationErrorHandlerContinuation.AbortHandling:
                        // Exit, response was already handled
                        return;
                    case ValidationErrorHandlerContinuation.IgnoreValidationFailure:
                        // Fallthrough into NextStep()
                        break;
                    default:
                        throw new ArgumentOutOfRangeException();
                }
            }

            try
            {
                await (multiType?.InvokeMember("NextStep",
                    BindingFlags.Static | BindingFlags.Public | BindingFlags.InvokeMethod, null, null,
                    new object[] { Context, validation, modal }) as Task);

            }
            catch (Exception ex)
            {
                SentrySdk.CaptureException(ex);
            }
        }

        // This is called for all component interactions set by MultiStepComponentInteractionAssociationAttribute
        public async Task HandleComponentInteraction()
        {
            await HandleComponentInteraction(Context, null, _serviceProvider, null);
        }

        public static async Task HandleComponentInteraction(IInteractionContext context, object[] args, IServiceProvider serviceProvider, ICommandInfo commandInfo)
        {
            var multiType = ModalDirectory.Instance.GetMultiModalTypeFromComponentInteractionId((context.Interaction as IComponentInteraction).Data.CustomId);
            try
            {
                await (multiType?.InvokeMember("NextStep", BindingFlags.Static | BindingFlags.Public | BindingFlags.InvokeMethod, null, null, new object[] { context, null, null }) as Task);
            }
            catch (Exception ex)
            {
                SentrySdk.CaptureException(ex);
            }
        }

